 * وتدعم أيضاً MySQL في حال تم تفعيلها
 */

require_once __DIR__ . '/../config.php';

try {
    if (DB_TYPE === 'sqlite') {
        $sqlite_path = SQLITE_FILE;
        $data_dir = dirname($sqlite_path);

        // في بيئة Vercel Serverless تكون ملفات المشروع للقراءة فقط (Read-Only)
        // لتفادي خطأ: attempt to write a readonly database نقوم بنسخ واستخدام النسخة في /tmp القابلة للكتابة
        $is_readonly_env = !empty(getenv('VERCEL'))
            || !empty(getenv('AWS_LAMBDA_FUNCTION_NAME'))
            || !is_writable($data_dir)
            || (file_exists($sqlite_path) && !is_writable($sqlite_path));

        if ($is_readonly_env) {
            $tmp_sqlite = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'database.sqlite';
            if (!file_exists($tmp_sqlite) || (file_exists($sqlite_path) && filemtime($sqlite_path) > filemtime($tmp_sqlite))) {
                @copy($sqlite_path, $tmp_sqlite);
            }
            $sqlite_path = $tmp_sqlite;
        } else {
            // التأكد من وجود مجلد data محلياً إن أمكن
            if (!is_dir($data_dir)) {
                @mkdir($data_dir, 0755, true);
            }
        }

        // الاتصال بقاعدة بيانات SQLite الداخلية
        $pdo = new PDO("sqlite:" . $sqlite_path);
        $pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
        $pdo->setAttribute(PDO::ATTR_DEFAULT_FETCH_MODE, PDO::FETCH_ASSOC);

        // تفعيل المفاتيح الأجنبية وأداء SQLite
        $pdo->exec("PRAGMA foreign_keys = ON;");

        // التحقق مما إذا كانت الجداول منشأة، إذا لم تكن موجودة نقوم بالإنشاء والتغذية التلقائية
        $check = $pdo->query("SELECT name FROM sqlite_master WHERE type='table' AND name='settings'")->fetch();
        if (!$check) {
            init_sqlite_database($pdo);
        }

    } else {
        // اتصال MySQL السحابي
        $dsn = "mysql:host=" . DB_HOST . ";port=" . DB_PORT . ";dbname=" . DB_NAME . ";charset=" . DB_CHARSET;
        
        $opt_init = defined('Pdo\Mysql::ATTR_INIT_COMMAND') ? Pdo\Mysql::ATTR_INIT_COMMAND : (defined('PDO::MYSQL_ATTR_INIT_COMMAND') ? @constant('PDO::MYSQL_ATTR_INIT_COMMAND') : 1002);
        $opt_ssl_ca = defined('Pdo\Mysql::ATTR_SSL_CA') ? Pdo\Mysql::ATTR_SSL_CA : (defined('PDO::MYSQL_ATTR_SSL_CA') ? @constant('PDO::MYSQL_ATTR_SSL_CA') : 1000);
        $opt_ssl_verify = defined('Pdo\Mysql::ATTR_SSL_VERIFY_SERVER_CERT') ? Pdo\Mysql::ATTR_SSL_VERIFY_SERVER_CERT : (defined('PDO::MYSQL_ATTR_SSL_VERIFY_SERVER_CERT') ? @constant('PDO::MYSQL_ATTR_SSL_VERIFY_SERVER_CERT') : 1014);
        $opt_multi = defined('Pdo\Mysql::ATTR_MULTI_STATEMENTS') ? Pdo\Mysql::ATTR_MULTI_STATEMENTS : (defined('PDO::MYSQL_ATTR_MULTI_STATEMENTS') ? @constant('PDO::MYSQL_ATTR_MULTI_STATEMENTS') : 1013);

        $options = [
            PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            PDO::ATTR_EMULATE_PREPARES   => false,
            $opt_init                    => "SET NAMES " . DB_CHARSET . " COLLATE " . DB_CHARSET . "_unicode_ci",
            $opt_ssl_verify              => false,
            $opt_multi                   => true,
        ];

        $ca_file = __DIR__ . '/../data/cacert.pem';
        if (file_exists($ca_file)) {
            $options[$opt_ssl_ca] = $ca_file;
        }

        $pdo = new PDO($dsn, DB_USER, DB_PASS, $options);

        // التحقق من وجود الجداول في MySQL والتغذية التلقائية إن كانت فارغة
        try {
            $check = $pdo->query("SHOW TABLES LIKE 'settings'")->fetch();
            if (!$check) {
                init_mysql_database($pdo);
            }
        } catch (Exception $ignored) {}
    }

